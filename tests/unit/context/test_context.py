# Splicing (FR-006, FR-009)

OWN = "# My instructions\n\nKeep answers short.\n"


@spec("FR-006")
def test_a_new_file_holds_only_the_block() -> None:
    assert splice(None, BLOCK) == BLOCK
    assert splice("", BLOCK) == BLOCK


@spec("FR-006")
def test_the_block_is_appended_after_a_blank_line() -> None:
    assert splice(OWN, BLOCK) == OWN + "\n" + BLOCK
    assert splice("Keep answers short.", BLOCK) == "Keep answers short.\n\n" + BLOCK


@spec("FR-006")
def test_the_block_is_replaced_in_place_and_nothing_else_changes() -> None:
    old = OWN + "\n" + f"{BEGIN}\nold content\n{END}\n" + "\nAfter the block.\n"

    assert splice(old, BLOCK) == OWN + "\n" + BLOCK + "\nAfter the block.\n"


@spec("FR-006")
def test_crlf_files_get_a_crlf_block() -> None:
    own = OWN.replace("\n", "\r\n")
    new = splice(own, BLOCK)

    assert new == own + "\r\n" + BLOCK.replace("\n", "\r\n")
    assert splice(new, BLOCK) == new


