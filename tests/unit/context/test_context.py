def target(workspace: Path) -> Path:
    return workspace / "claude" / "CLAUDE.md"


def code_from(out: str) -> str:
    match = re.search(r"^Confirmation code: ([0-9a-f]{12})$", out, re.MULTILINE)
    assert match is not None, out
    return match.group(1)


